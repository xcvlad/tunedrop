def _svg(name: str, color: str, stroke: float) -> bytes:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" '
        f'stroke="{color}" stroke-width="{stroke}" stroke-linecap="round" '
        f'stroke-linejoin="round">{_PATHS[name]}</svg>'
    ).encode()


@lru_cache(maxsize=128)
def pixmap(name: str, size: int = 18, color: str = theme.TEXT, stroke: float = 2.0) -> QPixmap:
    renderer = QSvgRenderer(QByteArray(_svg(name, color, stroke)))
    ratio = 2  # nitidez en pantallas HiDPI
    pix = QPixmap(size * ratio, size * ratio)
    pix.fill(Qt.transparent)
    painter = QPainter(pix)
    renderer.render(painter, QRectF(0, 0, size * ratio, size * ratio))
    painter.end()
    pix.setDevicePixelRatio(ratio)
    return pix


def icon(name: str, size: int = 18, color: str = theme.TEXT, stroke: float = 2.0) -> QIcon:
    return QIcon(pixmap(name, size, color, stroke))
